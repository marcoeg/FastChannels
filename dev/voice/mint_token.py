"""Mint a LiveKit room token and write the browser client config.

Usage: ./mint_token.py [days]   (default 30)
Writes dev/voice/client/config.js (git-excluded) with the wss URL and two
tokens: room "voice" (normal use) and room "test-plan" (the page opened
with ?test — the agent's test mode).
"""

import json
import sys
import time
from pathlib import Path

import jwt

HERE = Path(__file__).parent
env = dict(
    line.split("=", 1)
    for line in (HERE / ".env").read_text().splitlines()
    if line and not line.startswith("#") and "=" in line
)

days = int(sys.argv[1]) if len(sys.argv) > 1 else 30
now = int(time.time())
def mint(room: str) -> str:
    return jwt.encode(
        {
            "iss": env["LIVEKIT_API_KEY"].strip(),
            "sub": "marco",
            "name": "Marco",
            "nbf": now - 60,
            "exp": now + days * 86400,
            "video": {
                "room": room,
                "roomJoin": True,
                "canPublish": True,
                "canSubscribe": True,
            },
        },
        env["LIVEKIT_API_SECRET"].strip(),
        algorithm="HS256",
    )


config = {
    # The browser reaches LiveKit through caddy's TLS proxy on 8443.
    "url": "wss://" + "{HOST}" + ":8443",
    "token": mint("voice"),
    # Opened with ?test the page joins room "test-plan": the agent's test
    # mode (marked traces, separate memory graph) — see TEST-SCRIPT.md.
    "testToken": mint("test-plan"),
    # The page shows "Pair a TV" (a code box, claimed through caddy on the
    # remote relay) only for the minny-client viewer.
    "pairing": env.get("VOICE_TV", "").strip() == "minny",
}
out = HERE / "client" / "config.js"
out.write_text(
    "// generated by mint_token.py — git-excluded\n"
    "window.VOICE_CONFIG = " + json.dumps(config, indent=2) + ";\n"
    "// {HOST} is replaced at load time with location.hostname\n"
)
print(f"token valid {days} days -> {out}")
