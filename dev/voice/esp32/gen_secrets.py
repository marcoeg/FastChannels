#!/usr/bin/env -S uv run --quiet --script
# /// script
# requires-python = ">=3.11"
# dependencies = ["pyjwt"]
# ///
"""Generate sdkconfig.secrets.defaults for the Minny satellite firmware.

Mints a long-lived LiveKit token (identity "esp32", room "voice") using the
API key/secret from dev/voice/.env — same signing scheme as mint_token.py —
and writes it together with the WiFi credentials.

Usage:
  ./gen_secrets.py --ssid "MyNet" --password "secret" [--days 365]
                   [--room voice] [--identity esp32]

Re-running without --ssid/--password keeps the WiFi lines already present in
an existing sdkconfig.secrets.defaults (token is always re-minted).
NOTE: the ESP32-S3 radio is 2.4 GHz only — use the 2.4 GHz SSID.
"""

import argparse
import re
import time
from pathlib import Path

import jwt

HERE = Path(__file__).parent
OUT = HERE / "sdkconfig.secrets.defaults"

env = dict(
    line.split("=", 1)
    for line in (HERE.parent / ".env").read_text().splitlines()
    if line and not line.startswith("#") and "=" in line
)

ap = argparse.ArgumentParser()
ap.add_argument("--ssid")
ap.add_argument("--password")
ap.add_argument("--days", type=int, default=365)
# Own room on purpose: the ESP32 SDK subscribes to exactly ONE remote audio
# track, so sharing room "voice" with the phone/browser could latch the
# satellite onto the phone's mic instead of the agent's voice. The worker
# auto-dispatches to any room.
ap.add_argument("--room", default="speaker")
ap.add_argument("--identity", default="esp32")
args = ap.parse_args()

ssid, password = args.ssid, args.password
if (ssid is None or password is None) and OUT.exists():
    old = OUT.read_text()
    if ssid is None:
        m = re.search(r'CONFIG_LK_EXAMPLE_WIFI_SSID="(.*)"', old)
        ssid = m.group(1) if m else None
    if password is None:
        m = re.search(r'CONFIG_LK_EXAMPLE_WIFI_PASSWORD="(.*)"', old)
        password = m.group(1) if m else None
if ssid is None:
    ssid = "SET-ME-2.4GHZ-SSID"
if password is None:
    password = "SET-ME"

now = int(time.time())
token = jwt.encode(
    {
        "iss": env["LIVEKIT_API_KEY"].strip(),
        "sub": args.identity,
        "name": "Speaker",
        "nbf": now - 60,
        "exp": now + args.days * 86400,
        "video": {
            "room": args.room,
            "roomJoin": True,
            "canPublish": True,
            "canSubscribe": True,
        },
    },
    env["LIVEKIT_API_SECRET"].strip(),
    algorithm="HS256",
)

OUT.write_text(
    "# Generated by gen_secrets.py — git-excluded. Do not commit.\n"
    f'# Token: identity "{args.identity}", room "{args.room}", '
    f"valid {args.days} days from {time.strftime('%Y-%m-%d')}.\n"
    "CONFIG_LK_EXAMPLE_USE_WIFI=y\n"
    f'CONFIG_LK_EXAMPLE_WIFI_SSID="{ssid}"\n'
    f'CONFIG_LK_EXAMPLE_WIFI_PASSWORD="{password}"\n'
    f'CONFIG_LK_TOKEN="{token}"\n'
)
print(f"wrote {OUT}")
if "SET-ME" in ssid or "SET-ME" in password:
    print("WiFi credentials are placeholders — re-run with --ssid/--password "
          "(2.4 GHz network) before flashing.")
